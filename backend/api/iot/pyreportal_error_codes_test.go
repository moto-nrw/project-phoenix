// Package iot — PyrePortal error-code guard.
//
// This is a regression tripwire, not a behavioral test. The PyrePortal kiosk
// app (PyrePortal/src/services/apiErrors.ts) branches on the registry code of
// an /api/iot/* refusal. If the backend stops emitting one of these codes,
// the kiosk silently falls back to its generic message. Since #2520 the
// detail text is developer diagnostics and no contract (ADR 0006), so only
// the codes are guarded.
//
// The guard reads every non-test .go file under api/iot/ (all sub-packages,
// so it survives package moves/merges) plus the module sources whose codes
// surface through IoT routes, and asserts every code is still present
// somewhere in that corpus.
//
// The codes below must match the lines of api/testdata/iot_error_codes.golden
// one to one. That golden, generated by api.TestFullProductionRouterGolden,
// pins each code to the Go declaration that emits it, so a one-sided edit of
// either list fails here.
package iot

import (
	"os"
	"path/filepath"
	"runtime"
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

// pyreportalErrorCodes are the registry codes the kiosk branches on.
var pyreportalErrorCodes = []string{
	// Check-in conflicts (POST /checkin).
	"iot.activity_capacity_exceeded",
	"iot.room_capacity_exceeded",
	"iot.student_already_active",

	// Staff clock (POST /staff-clock), STAFF_CLOCK_MESSAGES.
	"iot.invalid_staff_clock_request",
	"iot.invalid_rfid_tag",
	"iot.rfid_tag_not_found",
	"iot.rfid_tag_inactive",
	"iot.rfid_tag_not_staff",
	"iot.planned_start_not_reached",
	"iot.deviation_reason_required",
	"iot.invalid_staff_clock_state",

	// Destination booking into a released room (POST /move-to-room, #3067).
	"iot.room_not_found",
	"rooms.not_released",
	"iot.student_not_present",
	"iot.open_room_binary_mode",
}

// extraGuardSources are files OUTSIDE api/iot whose codes surface through
// IoT routes. Paths are relative to the backend module root.
var extraGuardSources = []string{
	// The destination booking into released rooms (#3067).
	"modules/devicescan/open_room.go",
}

// TestPyrePortalErrorCodesGuard asserts every code PyrePortal branches on is
// still present in the IoT-facing sources. The test name deliberately
// contains "PyrePortal" so failures in CI logs land the reader directly on
// this file — and the file-top comment explains the coupling.
func TestPyrePortalErrorCodesGuard(t *testing.T) {
	t.Parallel()

	_, thisFile, _, ok := runtime.Caller(0)
	require.True(t, ok, "runtime.Caller failed — cannot locate guard sources")
	iotDir := iotSourceDir(t, thisFile)               // backend/api/iot
	backendRoot := filepath.Dir(filepath.Dir(iotDir)) // backend/

	var blob strings.Builder

	// Every non-test .go file under api/iot/ — package-layout agnostic, so
	// a sub-package consolidation cannot silently blind the guard.
	walkErr := filepath.WalkDir(iotDir, func(path string, d os.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() || !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}
		data, readErr := os.ReadFile(path) // #nosec G304 -- repo-local source scan
		if readErr != nil {
			return readErr
		}
		blob.Write(data)
		blob.WriteByte('\n')
		return nil
	})
	require.NoError(t, walkErr, "scanning api/iot sources")

	for _, rel := range extraGuardSources {
		data, err := os.ReadFile(filepath.Join(backendRoot, rel)) // #nosec G304 -- repo-local source scan
		require.NoErrorf(t, err, "reading guard source %s — if the file moved, update extraGuardSources in the same commit", rel)
		blob.Write(data)
		blob.WriteByte('\n')
	}
	corpus := blob.String()

	assertReconciledWithGolden(t, filepath.Join(backendRoot, "api", "testdata", "iot_error_codes.golden"))

	for _, want := range pyreportalErrorCodes {
		assert.Truef(t, strings.Contains(corpus, `"`+want+`"`),
			"PyrePortal branches on the stable IoT error code %q. Update the backend and "+
				"PyrePortal mapping together if this contract changes.",
			want,
		)
	}
}

// The three check-in conflicts, 8 of the 9 STAFF_CLOCK_MESSAGES and the four
// OPEN_ROOM_MESSAGES of the destination booking (#3067).
const wantPyrePortalErrorCodes = 15

// assertReconciledWithGolden fails when this guard's list and the lines of
// the IoT error-code golden disagree in either direction.
func assertReconciledWithGolden(t *testing.T, goldenPath string) {
	t.Helper()

	assert.Lenf(t, pyreportalErrorCodes, wantPyrePortalErrorCodes,
		"pyreportalErrorCodes changed size. Change the code in PyrePortal/src/services/apiErrors.ts, "+
			"api/iot_error_codes_golden_test.go and here together.")

	data, err := os.ReadFile(goldenPath) // #nosec G304 -- repo-local testdata
	require.NoError(t, err, "reading the IoT error-code golden")
	var golden []string
	for line := range strings.Lines(string(data)) {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		kind, rest, ok := strings.Cut(line, ": ")
		require.Truef(t, ok && kind == "code", "malformed golden line %q", line)
		code, _, ok := strings.Cut(rest, " -> ")
		require.Truef(t, ok, "malformed golden line %q", line)
		golden = append(golden, code)
	}

	assert.ElementsMatch(t, golden, pyreportalErrorCodes,
		"this guard and api/testdata/iot_error_codes.golden disagree. Both mirror "+
			"PyrePortal/src/services/apiErrors.ts; change the golden table, this list and PyrePortal together.")
}

func iotSourceDir(t *testing.T, callerPath string) string {
	t.Helper()

	if filepath.IsAbs(callerPath) {
		if _, err := os.Stat(callerPath); err == nil {
			return filepath.Dir(callerPath)
		}
	}

	wd, err := os.Getwd()
	require.NoError(t, err, "resolve working directory")
	moduleRoot := wd
	for {
		if _, err := os.Stat(filepath.Join(moduleRoot, "go.mod")); err == nil {
			return filepath.Join(moduleRoot, "api", "iot")
		}
		parent := filepath.Dir(moduleRoot)
		require.NotEqual(t, moduleRoot, parent, "resolve module root from %s", wd)
		moduleRoot = parent
	}
}
