// IoT error-code golden — issues #3419, #2520.
//
// PyrePortal branches on the registry code of an /api/iot/* refusal
// (errorCodes.generated.ts, synced from error-registry.json); since #2520 the
// text in `detail` is developer diagnostics and no contract (ADR 0006).
// testdata/iot_error_codes.golden pins every code the kiosk branches on to
// the Go declaration that emits it.
//
// Each line is derived from the source: the test parses the named file,
// finds the first string literal (never a comment or a log message) that
// equals the code, and records the constant, variable or function that
// declares it. Removing the code turns its line into "NOT EMITTED"; moving
// it to another declaration changes the symbol. Both are golden diffs.
package api

import (
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"path"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"
)

// iotErrorContract is one registry code PyrePortal branches on and the
// canonical source identity whose declaration emits it on an /api/iot
// route. Physical source lookup follows the relocations below.
type iotErrorContract struct {
	code string
	file string
}

const (
	checkinCapacity    = "api/iot/checkin/capacity_errors.go"
	staffClockErrors   = "api/iot/staffclock/errors.go"
	deviceScanOpenRoom = "modules/devicescan/open_room.go"
)

// Keep declaration identities in the golden stable across ADR 0020 moves.
// Only the physical source lookup follows the relocated packages.
var iotErrorCodeSourceFiles = map[string]string{
	checkinCapacity:  "modules/devicescan/http/checkin/capacity_errors.go",
	staffClockErrors: "modules/devicescan/http/staffclock/errors.go",
}

// iotErrorCodes are the registry codes the kiosk branches on: the check-in
// conflicts, STAFF_CLOCK_MESSAGES and the destination booking into a
// released room.
var iotErrorCodes = []iotErrorContract{
	{"iot.activity_capacity_exceeded", checkinCapacity},
	{"iot.room_capacity_exceeded", checkinCapacity},
	{"iot.student_already_active", checkinCapacity},

	{"iot.invalid_staff_clock_request", staffClockErrors},
	{"iot.invalid_rfid_tag", staffClockErrors},
	{"iot.rfid_tag_not_found", staffClockErrors},
	{"iot.rfid_tag_inactive", staffClockErrors},
	{"iot.rfid_tag_not_staff", staffClockErrors},
	{"iot.planned_start_not_reached", staffClockErrors},
	{"iot.deviation_reason_required", staffClockErrors},
	{"iot.invalid_staff_clock_state", staffClockErrors},

	// Destination booking into a released room (POST /move-to-room, #3067).
	{"iot.room_not_found", deviceScanOpenRoom},
	{"rooms.not_released", deviceScanOpenRoom},
	{"iot.student_not_present", deviceScanOpenRoom},
	{"iot.open_room_binary_mode", deviceScanOpenRoom},
}

const iotErrorCodesHeader = `# PyrePortal error-code contract for /api/iot/* (issues #3419, #2520).
# Consumer: ../PyrePortal/src/services/apiErrors.ts, which branches on the
# registry code; the detail text is diagnostics and no contract.
# Changing a line here is a coordinated change in the backend and PyrePortal repos.
# Generated by TestFullProductionRouterGolden/contracts/IoT_error_code_declarations.
`

func checkIoTErrorCodesGolden(t *testing.T) {
	t.Parallel()

	files := map[string]*declaredLiterals{}
	resolve := func(c iotErrorContract) string {
		decls, ok := files[c.file]
		if !ok {
			decls = parseDeclaredLiterals(t, c.file)
			files[c.file] = decls
		}
		if symbol := decls.find(c.code); symbol != "" {
			return fmt.Sprintf("%s.%s (%s)", path.Dir(c.file), symbol, path.Base(c.file))
		}
		return fmt.Sprintf("NOT EMITTED by %s", c.file)
	}

	lines := make([]string, 0, len(iotErrorCodes))
	for _, c := range iotErrorCodes {
		lines = append(lines, fmt.Sprintf("code: %s -> %s", c.code, resolve(c)))
	}
	sort.Strings(lines)

	compareGolden(t, filepath.Join("testdata", "iot_error_codes.golden"), iotErrorCodesHeader+strings.Join(lines, "\n")+"\n",
		"a registry code PyrePortal branches on moved or no longer reaches an /api/iot route. The kiosk "+
			"compares it exactly in PyrePortal/src/services/apiErrors.ts. Restore the code, or change "+
			"PyrePortal in step and regenerate with -update-goldens")
}

// declaredLiterals holds the string literals of one Go file with the name of
// the constant, variable or function that declares each.
type declaredLiterals struct {
	literals []string
	symbols  []string
}

func (d *declaredLiterals) find(code string) string {
	for i, literal := range d.literals {
		if literal == code {
			return d.symbols[i]
		}
	}
	return ""
}

func parseDeclaredLiterals(t *testing.T, rel string) *declaredLiterals {
	t.Helper()
	source := rel
	if relocated, ok := iotErrorCodeSourceFiles[rel]; ok {
		source = relocated
	}
	file, err := parser.ParseFile(token.NewFileSet(), filepath.Join("..", filepath.FromSlash(source)), nil, parser.SkipObjectResolution)
	require.NoErrorf(t, err, "parse %s — if the file moved, update the IoT error contract table in the same commit", rel)

	decls := &declaredLiterals{}
	collect := func(symbol string, node ast.Node) {
		ast.Inspect(node, func(n ast.Node) bool {
			if call, ok := n.(*ast.CallExpr); ok && isLogCall(call) {
				return false
			}
			lit, ok := n.(*ast.BasicLit)
			if !ok || lit.Kind != token.STRING {
				return true
			}
			value, err := strconv.Unquote(lit.Value)
			require.NoError(t, err)
			decls.literals = append(decls.literals, value)
			decls.symbols = append(decls.symbols, symbol)
			return true
		})
	}
	for _, decl := range file.Decls {
		switch decl := decl.(type) {
		case *ast.FuncDecl:
			collect(funcSymbol(decl), decl)
		case *ast.GenDecl:
			for _, spec := range decl.Specs {
				value, ok := spec.(*ast.ValueSpec)
				if !ok {
					continue
				}
				for i, expr := range value.Values {
					collect(value.Names[min(i, len(value.Names)-1)].Name, expr)
				}
			}
		}
	}
	return decls
}

// isLogCall reports slog-style calls whose message never reaches the client.
func isLogCall(call *ast.CallExpr) bool {
	selector, ok := call.Fun.(*ast.SelectorExpr)
	if !ok {
		return false
	}
	switch selector.Sel.Name {
	case "DebugContext", "InfoContext", "WarnContext", "ErrorContext":
		return true
	}
	return false
}

func funcSymbol(decl *ast.FuncDecl) string {
	if decl.Recv == nil || len(decl.Recv.List) == 0 {
		return decl.Name.Name
	}
	recv := decl.Recv.List[0].Type
	if star, ok := recv.(*ast.StarExpr); ok {
		recv = star.X
	}
	if index, ok := recv.(*ast.IndexExpr); ok {
		recv = index.X
	}
	if ident, ok := recv.(*ast.Ident); ok {
		return ident.Name + "." + decl.Name.Name
	}
	return decl.Name.Name
}
