package test

import (
	"io/fs"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// walkModuleRatchetSources shares the size, length and complexity surface.
// ADR 0087: scan every backend tree, not a list of today's policy packages.
// This conservative superset includes migrations, tools, generated sources,
// test support, hooks and testdata, independent of build tags and platform.
// New or relocated packages are covered without updating a selector list.
// Only _test.go and hidden directories remain excluded (as in ADR 0082).
func walkModuleRatchetSources(backendRoot string, visit func(path, rel string) error) error {
	return filepath.WalkDir(backendRoot, func(path string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() {
			if path != backendRoot && strings.HasPrefix(entry.Name(), ".") {
				return filepath.SkipDir
			}
			return nil
		}
		if !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") {
			return nil
		}
		rel, err := filepath.Rel(backendRoot, path)
		if err != nil {
			return err
		}
		return visit(path, filepath.ToSlash(rel))
	})
}

// Every source category must reject an unregistered file, long function and
// complex function, even in a future tree absent from policy.json (ADR 0087).
func TestModuleRootSourceRatchetsRejectNewViolations(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	for _, tree := range []string{"modules", "workflows", "roots", "api", "cmd"} {
		if err := os.MkdirAll(filepath.Join(root, tree), 0755); err != nil {
			t.Fatal(err)
		}
	}
	source := "//go:build testhooks\n\npackage fixture\n\nfunc Oversized(b bool) {\n" +
		strings.Repeat("if b {\nprintln(b)\n}\n", 16) +
		strings.Repeat("// body line\n", 14) + "}\n" + strings.Repeat("// padding\n", 800)
	paths := []string{
		"main.go", "roots/newbinding/nested/example.go", "api/nested/example.go", "cmd/nested/example.go",
		"modules/example/legacy/example.go", "workflows/example/example.go",
		"internal/example/nested/example.go", "database/migrations/example.go",
		"tenant/example.go", "realtime/example.go", "middleware/example.go",
		"analytics/example.go", "auth/example.go", "observability/example.go",
		"sharedkernel/example.go", "demoprofile/example.go", "seed/example.go",
		"test/example.go", "internal/architecture/testdata/example.go",
		"api/common/example.generated.go", "future-production-tree/nested/example.go",
		"internal/example/platform_darwin.go", "outside/ignored.go",
	}
	for _, rel := range paths {
		path := filepath.Join(root, rel)
		if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
			t.Fatal(err)
		}
		fixture := source
		if strings.HasSuffix(rel, ".generated.go") {
			fixture = "// Code generated by source-ratchet fixture. DO NOT EDIT.\n" + fixture
		}
		if err := os.WriteFile(path, []byte(fixture), 0600); err != nil {
			t.Fatal(err)
		}
	}
	for _, rel := range []string{"api/ignored_test.go", "roots/.hidden/ignored.go", ".hidden/ignored.go"} {
		path := filepath.Join(root, rel)
		if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(source), 0600); err != nil {
			t.Fatal(err)
		}
	}
	sizes, err := moduleFileSizeScan(root)
	if err != nil {
		t.Fatal(err)
	}
	lengths, err := moduleFuncLenScan(root)
	if err != nil {
		t.Fatal(err)
	}
	scores, err := moduleComplexityScan(root)
	if err != nil {
		t.Fatal(err)
	}
	for _, rel := range paths {
		if sizes[rel] <= moduleFileSizeThreshold || lengths[rel+":Oversized"] <= moduleFuncLenThreshold || scores[rel+":Oversized"] <= moduleComplexityThreshold {
			t.Errorf("source violation escaped: %s (size %d, length %d, complexity %d)", rel, sizes[rel], lengths[rel+":Oversized"], scores[rel+":Oversized"])
		}
	}
	if len(sizes) != len(paths) || len(lengths) != len(paths) || len(scores) != len(paths) {
		t.Fatalf("unexpected scope: %v, %v, %v", sizes, lengths, scores)
	}
	if len(moduleFileSizeViolations(sizes, nil)) != len(paths) || len(moduleFuncLenViolations(lengths, nil)) != len(paths) || len(moduleComplexityViolations(scores, nil)) != len(paths) {
		t.Fatal("unregistered source violations must fail all three ratchets")
	}
}
