import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, posix, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import ts from "typescript";

const defaultDirectory = fileURLToPath(
  new URL("../src/components/help/", import.meta.url),
);

function collectImports(statement, bindings, file) {
  const clause = statement.importClause;
  if (!clause?.namedBindings || !ts.isNamedImports(clause.namedBindings))
    throw new Error(`${file}: article imports must use named bindings`);
  if (
    !clause.isTypeOnly &&
    clause.namedBindings.elements.every((element) => element.isTypeOnly)
  )
    throw new Error(
      `${file}: empty or inline-type-only value imports must use import type`,
    );
  const original = statement.moduleSpecifier.text;
  const modulePath = original.startsWith(".")
    ? `./${posix.normalize(posix.join("articles", original))}`
    : original;
  for (const element of clause.namedBindings.elements) {
    const name = element.name.text;
    const imported = element.propertyName?.text ?? name;
    const typeOnly = clause.isTypeOnly || element.isTypeOnly;
    const previous = bindings.get(name);
    if (
      previous &&
      (previous.module !== modulePath || previous.imported !== imported)
    )
      throw new Error(`${file}: conflicting article import ${name}`);
    bindings.set(name, {
      module: modulePath,
      imported,
      typeOnly: previous ? previous.typeOnly && typeOnly : typeOnly,
    });
  }
}

function renderImports(bindings) {
  const groups = new Map();
  for (const [name, binding] of [...bindings].sort(([a], [b]) =>
    a.localeCompare(b, "en"),
  )) {
    const key = `${binding.typeOnly ? "type " : ""}${JSON.stringify(binding.module)}`;
    const group = groups.get(key) ?? {
      module: binding.module,
      typeOnly: binding.typeOnly,
      names: [],
    };
    group.names.push(
      binding.imported === name ? name : `${binding.imported} as ${name}`,
    );
    groups.set(key, group);
  }
  return [...groups.values()].map(
    (group) =>
      `import ${group.typeOnly ? "type " : ""}{ ${group.names.join(", ")} } from ${JSON.stringify(group.module)};`,
  );
}

function articleDerivative(file, text, bindings, names) {
  const ast = ts.createSourceFile(file, text, ts.ScriptTarget.Latest, true);
  if (ast.parseDiagnostics.length)
    throw new Error(`${file}: malformed help article`);
  const factories = ast.statements.filter(
    (statement) => !ts.isImportDeclaration(statement),
  );
  const factory = factories[0];
  if (
    factories.length !== 1 ||
    !factory ||
    !ts.isFunctionDeclaration(factory) ||
    !factory.name ||
    !factory.modifiers?.some(
      (modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword,
    )
  )
    throw new Error(
      `${file}: expected exactly one exported article factory and imports only`,
    );
  const name = factory.name.text;
  if (names.has(name))
    throw new Error(`Duplicate help article factory: ${name}`);
  names.add(name);
  for (const statement of ast.statements)
    if (ts.isImportDeclaration(statement))
      collectImports(statement, bindings, file);
  const implementation = factory.getText(ast).replace(/^export\s+/, "");
  const comment = text
    .slice(factory.getFullStart(), factory.getStart(ast))
    .trim();
  // A named, erased import records the actual authored export as a type edge.
  // No article module or per-article wrapper survives TypeScript emission.
  const authored = `authored_${name}`;
  if (bindings.has(authored))
    throw new Error(`${file}: conflicting article contract ${authored}`);
  bindings.set(authored, {
    module: `./articles/${file.slice(0, -3)}`,
    imported: name,
    typeOnly: true,
  });
  return `${comment}\nexport const ${name} = (${implementation}) satisfies typeof ${authored};`;
}

export async function synchronizeHelpIndex({
  directory = defaultDirectory,
  check = false,
} = {}) {
  const folder = join(directory, "articles");
  const files = readdirSync(folder)
    .filter((file) => file.endsWith(".ts"))
    .sort();
  if (!files.length) throw new Error("Help article sources are empty");
  const names = new Set();
  const bindings = new Map();
  const articles = files.map((file) =>
    articleDerivative(
      file,
      readFileSync(join(folder, file), "utf8"),
      bindings,
      names,
    ),
  );
  const target = join(directory, "help-articles.generated.ts");
  const generated = await format(
    [
      "// Code generated by scripts/generate-help-index.mjs; DO NOT EDIT.",
      ...renderImports(bindings),
      ...articles,
    ].join("\n\n") + "\n",
    { ...(await resolveConfig(target)), plugins: [], filepath: target },
  );
  if (check) {
    let existing = "";
    try {
      existing = readFileSync(target, "utf8");
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    if (existing !== generated)
      throw new Error(
        "Help article index is stale. Run pnpm generate:help-index.",
      );
  } else writeFileSync(target, generated);
  return names;
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  await synchronizeHelpIndex({ check: process.argv.includes("--check") });
}
