import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";
import ts from "typescript";

const defaultDirectory = fileURLToPath(
  new URL("../src/components/help/", import.meta.url),
);

export async function synchronizeHelpIndex({
  directory = defaultDirectory,
  check = false,
} = {}) {
  const folder = join(directory, "articles");
  const files = readdirSync(folder)
    .filter((file) => file.endsWith(".ts"))
    .sort();
  if (!files.length) throw new Error("Help article sources are empty");
  const names = new Set();
  const lines = [
    "// Code generated by scripts/generate-help-index.mjs; DO NOT EDIT.",
  ];
  for (const file of files) {
    const ast = ts.createSourceFile(
      file,
      readFileSync(join(folder, file), "utf8"),
      ts.ScriptTarget.Latest,
      true,
    );
    const exported = ast.statements.filter(
      (statement) =>
        ts.isFunctionDeclaration(statement) &&
        statement.modifiers?.some(
          (modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword,
        ),
    );
    if (exported.length !== 1 || !exported[0].name)
      throw new Error(`${file}: expected exactly one exported article factory`);
    const name = exported[0].name.text;
    if (names.has(name))
      throw new Error(`Duplicate help article factory: ${name}`);
    names.add(name);
    lines.push(
      `export { ${name} } from ${JSON.stringify(`./articles/${file.slice(0, -3)}`)};`,
    );
  }
  const target = join(directory, "help-articles.generated.ts");
  const generated = await format(lines.join("\n") + "\n", {
    ...(await resolveConfig(target)),
    plugins: [],
    filepath: target,
  });
  if (check) {
    let existing = "";
    try {
      existing = readFileSync(target, "utf8");
    } catch {
      /* A missing index is stale. */
    }
    if (existing !== generated)
      throw new Error(
        "Help article index is stale. Run pnpm generate:help-index.",
      );
  } else writeFileSync(target, generated);
  return names;
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  await synchronizeHelpIndex({ check: process.argv.includes("--check") });
}
