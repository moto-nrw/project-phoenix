import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

/** The portals whose host the proxy rewrites onto app/<portal>/. */
export const PORTALS = ["caterer", "operator", "parents", "school", "traeger"];

const defaultAppDirectory = fileURLToPath(new URL("../src/app/", import.meta.url));
const defaultTarget = fileURLToPath(
  new URL("../src/proxy-pages.generated.ts", import.meta.url),
);
const ROUTE_FILE = /^(page|route)\.(tsx?|jsx?|mdx)$/;

/** The first URL segments under app/<portal>/ that lead to a page or route.
 * Route groups add no segment and private folders no route, as in the App
 * Router. A dynamic first segment would make every path a page, so the proxy
 * could no longer tell a page from a stray path. */
export function portalPages(appDirectory, portal) {
  const pages = new Set();
  const visit = (directory, firstSegment) => {
    for (const entry of readdirSync(directory, { withFileTypes: true })) {
      if (entry.isFile()) {
        if (firstSegment && ROUTE_FILE.test(entry.name)) pages.add(firstSegment);
        continue;
      }
      if (!entry.isDirectory()) continue;
      const name = entry.name;
      if (name.startsWith("_") || name.startsWith("@")) continue;
      const isGroup = name.startsWith("(") && name.endsWith(")");
      if (!firstSegment && !isGroup && name.startsWith("["))
        throw new Error(
          `app/${portal}/${name}: a dynamic first segment cannot be routed by host`,
        );
      visit(
        join(directory, name),
        firstSegment ?? (isGroup ? undefined : `/${name}`),
      );
    }
  };
  visit(join(appDirectory, portal), undefined);
  return [...pages].sort();
}

export async function synchronizePortalPages({
  appDirectory = defaultAppDirectory,
  target = defaultTarget,
  check = false,
} = {}) {
  const entries = PORTALS.map(
    (portal) =>
      `  ${portal}: ${JSON.stringify(portalPages(appDirectory, portal))},`,
  );
  const generated = await format(
    [
      "// Code generated by scripts/generate-portal-pages.mjs; DO NOT EDIT.",
      "// The first path segments of the pages under app/<portal>/, which the",
      "// proxy rewrites on the portal's host. Run pnpm generate:portal-pages.",
      "export const PORTAL_PAGES = {",
      ...entries,
      "} as const;",
    ].join("\n") + "\n",
    { ...(await resolveConfig(target)), plugins: [], filepath: target },
  );
  if (!check) {
    writeFileSync(target, generated);
    return;
  }
  let existing = "";
  try {
    existing = readFileSync(target, "utf8");
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
  if (existing !== generated)
    throw new Error(
      "Proxy page list is stale. Run pnpm generate:portal-pages.",
    );
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  await synchronizePortalPages({ check: process.argv.includes("--check") });
}
