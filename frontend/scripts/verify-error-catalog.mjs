import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

const registry = JSON.parse(
  await readFile(new URL("../../error-registry.json", import.meta.url), "utf8"),
);
const locales = JSON.parse(
  await readFile(
    new URL("../../backend/localization/locales.json", import.meta.url),
    "utf8",
  ),
);
const allowedClasses = new Set([
  "input",
  "permission",
  "business_rejection",
  "unavailable",
  "server",
]);
const failures = [];
const runtimeCatalog = {};

for (const { code: locale } of locales) {
  const messages = JSON.parse(
    await readFile(
      new URL(`../src/i18n/messages/${locale}.json`, import.meta.url),
      "utf8",
    ),
  );
  const catalog = messages.errorCatalog;
  const codes = catalog?.codes ?? {};
  const overrides = {};

  for (const entry of registry.codes) {
    const [area, name] = entry.code.split(".");
    const text = codes[area]?.[name];
    if (!allowedClasses.has(entry.class)) {
      failures.push(`${entry.code}: unknown class ${entry.class}`);
    }
    if (typeof text !== "string" || !text.trim()) {
      failures.push(`${locale}: ${entry.code}: missing text`);
      continue;
    }
    const allowedParameters = new Set(["object", ...entry.parameters]);
    for (const match of text.matchAll(/\{([^{}]+)\}/g)) {
      if (!allowedParameters.has(match[1])) {
        failures.push(
          `${locale}: ${entry.code}: unsupported parameter ${match[1]}`,
        );
      }
    }
    if (text !== catalog?.classes?.[entry.class]) {
      overrides[entry.code] = text;
    }
  }

  const registered = new Set(registry.codes.map((entry) => entry.code));
  for (const [area, entries] of Object.entries(codes)) {
    for (const name of Object.keys(entries)) {
      if (!registered.has(`${area}.${name}`)) {
        failures.push(`${locale}: ${area}.${name}: not in registry`);
      }
    }
  }
  for (const className of allowedClasses) {
    if (!catalog?.classes?.[className]?.trim()) {
      failures.push(`${locale}: ${className}: missing class fallback`);
    }
  }
  for (const action of [
    "retry",
    "copyRequestId",
    "requestId",
    "crash",
    "fieldCheck",
  ]) {
    if (
      typeof catalog?.actions?.[action] !== "string" ||
      !catalog.actions[action].trim()
    ) {
      failures.push(`${locale}: ${action}: missing action text`);
    }
  }
  runtimeCatalog[locale] = {
    classes: catalog?.classes,
    actions: catalog?.actions,
    codes: overrides,
  };
}

if (failures.length) {
  throw new Error(`Error catalog is incomplete:\n${failures.join("\n")}`);
}

const generatedUrl = new URL(
  "../src/lib/error-catalog.generated.ts",
  import.meta.url,
);
const generatedPath = fileURLToPath(generatedUrl);
const generated = await format(
  `// Code generated by scripts/verify-error-catalog.mjs --write; DO NOT EDIT.\nexport const ERROR_CATALOG = ${JSON.stringify(runtimeCatalog, null, 2)} as const;\n`,
  {
    ...(await resolveConfig(generatedPath)),
    filepath: generatedPath,
  },
);
if (process.argv.includes("--write")) {
  await writeFile(generatedUrl, generated);
} else {
  const existing = await readFile(generatedUrl, "utf8").catch(() => "");
  if (existing !== generated) {
    throw new Error(
      "Error runtime catalog is out of date. Run pnpm generate:error-catalog.",
    );
  }
}
