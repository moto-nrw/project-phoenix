// Build-time only: runtime/client modules consume compact generated derivatives.
import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const SEGMENT = /^[A-Za-z][A-Za-z0-9_]*$/;

function assertUniqueJsonKeys(text, file) {
  const ast = ts.parseJsonText(file, text);
  function visit(node) {
    if (ts.isObjectLiteralExpression(node)) {
      const keys = new Set();
      for (const property of node.properties) {
        const key = property.name?.text;
        if (keys.has(key))
          throw new Error(`${file}: duplicate JSON key ${key}`);
        keys.add(key);
      }
    }
    ts.forEachChild(node, visit);
  }
  visit(ast);
}

/** Each relative JSON path owns exactly that message subtree. */
export function readMessageSources(directory, prefix = "") {
  return readdirSync(join(directory, prefix), { withFileTypes: true })
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
    .flatMap((entry) => {
      const relative = prefix ? `${prefix}/${entry.name}` : entry.name;
      if (entry.isDirectory()) return readMessageSources(directory, relative);
      if (!entry.isFile() || !entry.name.endsWith(".json")) return [];
      const path = relative.slice(0, -5).split("/");
      if (path.some((segment) => !SEGMENT.test(segment)))
        throw new Error(`Invalid message source path: ${relative}`);
      const text = readFileSync(join(directory, relative), "utf8");
      const value = JSON.parse(text);
      assertUniqueJsonKeys(text, relative);
      return [{ file: relative, path, value }];
    });
}

function sourceTree(sources) {
  if (sources.length === 0) throw new Error("Locale has no message sources");
  const root = { children: new Map(), source: null };
  for (const source of sources) {
    let node = root;
    for (const part of source.path) {
      if (node.source)
        throw new Error(
          `Overlapping message sources: ${node.source.file} and ${source.file}`,
        );
      if (!node.children.has(part))
        node.children.set(part, { children: new Map(), source: null });
      node = node.children.get(part);
    }
    if (node.source || node.children.size)
      throw new Error(
        `Overlapping or duplicate message source: ${source.file}`,
      );
    node.source = source;
  }
  return root;
}

export function composeMessages(sources) {
  function value(node) {
    return node.source
      ? node.source.value
      : Object.fromEntries(
          [...node.children].map(([key, child]) => [key, value(child)]),
        );
  }
  return value(sourceTree(sources));
}

/** Type-only JSON edges preserve exact inference without shipping fragment modules. */
export function renderMessageFacade(sources, locale) {
  const names = new Map(
    sources.map((source) => [
      source,
      `fragment_${source.path.map((part) => `${part.length}_${part}`).join("_")}`,
    ]),
  );
  function expression(node) {
    if (node.source) return `typeof ${names.get(node.source)}`;
    return `{${[...node.children].map(([key, child]) => `${JSON.stringify(key)}: ${expression(child)}`).join(",")}}`;
  }
  const imports = sources
    .map(
      (source) =>
        `import type ${names.get(source)} from ${JSON.stringify(`./${locale}/${source.file}`)};`,
    )
    .join("\n");
  return `// Code generated by scripts/generate-message-index.mjs; DO NOT EDIT.\n${imports}\n\nconst messages = JSON.parse(${JSON.stringify(JSON.stringify(composeMessages(sources)))}) as ${expression(sourceTree(sources))};\nexport default messages;\n`;
}

export function assertLocaleDirectories(directory, locales) {
  const actual = readdirSync(directory, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
  const expected = [...locales].sort();
  if (JSON.stringify(actual) !== JSON.stringify(expected))
    throw new Error(
      `Message source locale directories differ from supported locales: expected ${expected.join(", ")}; found ${actual.join(", ")}`,
    );
}

export function readLocaleMessages(
  locale,
  directory = new URL("../src/i18n/messages/", import.meta.url),
) {
  return composeMessages(
    readMessageSources(
      join(
        typeof directory === "string" ? directory : fileURLToPath(directory),
        locale,
      ),
    ),
  );
}

function leafKeys(value, prefix = "") {
  if (value && typeof value === "object" && !Array.isArray(value))
    return Object.entries(value).flatMap(([key, child]) =>
      leafKeys(child, prefix ? `${prefix}.${key}` : key),
    );
  return [prefix];
}

export function assertMessageParity(catalogs, fallback) {
  if (!catalogs.has(fallback))
    throw new Error(`Missing fallback message catalog: ${fallback}`);
  const expected = new Set(leafKeys(catalogs.get(fallback)));
  const failures = [];
  for (const [locale, catalog] of catalogs) {
    const keys = new Set(leafKeys(catalog));
    const missing = [...expected].filter((key) => !keys.has(key));
    const extra = [...keys].filter((key) => !expected.has(key));
    if (missing.length)
      failures.push(`${locale}: missing keys ${missing.join(", ")}`);
    if (extra.length)
      failures.push(`${locale}: unexpected keys ${extra.join(", ")}`);
  }
  if (failures.length)
    throw new Error(
      `Message catalogs are out of sync with ${fallback}:\n${failures.join("\n")}`,
    );
}

/** Literal lazy imports are visible to both the bundler and reachability checks. */
export function renderMessageLoaders(locales) {
  return `// Code generated by scripts/generate-message-index.mjs; DO NOT EDIT.\nimport type { AppLocale } from "../locales";\nimport type { Messages } from "../locale-resolution";\n\nexport const messageLoaders = {\n${locales.map((locale) => `${JSON.stringify(locale)}: () => import(${JSON.stringify(`./${locale}.generated`)}),`).join("\n")}\n} satisfies Record<AppLocale, () => Promise<{default: Messages}>>;\n`;
}
