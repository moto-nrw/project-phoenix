#!/usr/bin/env node
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, readdirSync, realpathSync, unlinkSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { ERROR_CLASSES, goSymbol, readRegistry, validateRegistry } from "./error-registry.mjs";

export { validateRegistry } from "./error-registry.mjs";
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const header = "// Code generated by scripts/generate-error-codes.mjs; DO NOT EDIT.\n";

// Domains are stable addresses. Only a genuinely oversized domain is split,
// by code hash rather than ordinal position; other domains never move.
function partition(entries, name, depth = 0) {
  if (depth > 63) throw new Error(`cannot partition error codes for ${name}`);
  if (entries.length <= 300) return [[name, entries]];
  const buckets = new Map();
  for (const entry of entries) {
    const digit = createHash("sha256").update(entry.code).digest("hex")[depth];
    const bucket = buckets.get(digit) ?? [];
    bucket.push(entry);
    buckets.set(digit, bucket);
  }
  return [...buckets.entries()].sort(([a], [b]) => a.localeCompare(b)).flatMap(([digit, bucket]) =>
    partition(bucket, `${name}_${digit}`, depth + 1));
}

function goShard(name, entries) {
  const identifier = name.split("_").map((part) => part[0].toUpperCase() + part.slice(1)).join("");
  // Individual declarations have no shard-wide alignment. A long new symbol
  // cannot reformat existing constants or class mappings.
  return header + "package common\n\n" + entries.map((entry) =>
    `const ${goSymbol(entry.code)} = ${JSON.stringify(entry.code)}\n`).join("") + "\n" +
    `var errorCodeClasses${identifier} = []errorCodeClass{\n` + entries.map((entry) =>
      `\t{${goSymbol(entry.code)}, ${JSON.stringify(entry.class)}},\n`).join("") + "}\n\n" +
    "func init() {\n" +
    `\tfor _, entry := range errorCodeClasses${identifier} {\n` +
    "\t\terrorClassByCode[entry.code] = entry.class\n" +
    "\t}\n" + `\terrorCodeClasses${identifier} = nil\n` + "}\n";
}

function tsDomain(entries) {
  const codes = entries.length === 1
    ? `export const codes = [${JSON.stringify(entries[0].code)}] as const;\n\n`
    : "export const codes = [\n" + entries.map((entry) =>
      `  ${JSON.stringify(entry.code)},\n`).join("") + "] as const;\n\n";
  return header + codes +
    "export const classes = {\n" + entries.map((entry) =>
      `  ${JSON.stringify(entry.code)}: ${JSON.stringify(entry.class)},\n`).join("") + "} as const;\n\n" +
    "export const parameters = {\n" + entries.map((entry) => {
      const prefix = `  ${JSON.stringify(entry.code)}: `;
      const values = entry.parameters.map((parameter) => JSON.stringify(parameter));
      const inline = `[${values.join(", ")}]`;
      return prefix.length + inline.length + 1 <= 80
        ? `${prefix}${inline},\n`
        : `${prefix}[\n${values.map((value) => `    ${value},\n`).join("")}  ],\n`;
    }).join("") + "} as const;\n";
}

export function generate(registry) {
  const entries = validateRegistry(registry);
  const domains = new Map();
  for (const entry of entries) {
    const domain = entry.code.split(".")[0];
    const group = domains.get(domain) ?? [];
    group.push(entry);
    domains.set(domain, group);
  }
  const goFiles = {};
  const tsFiles = {};
  for (const [domain, group] of domains) {
    for (const [name, shard] of partition(group, domain)) {
      const file = `error_codes_${name}.generated.go`;
      if (file in goFiles) throw new Error(`colliding generated shard: ${file}`);
      goFiles[file] = goShard(name, shard);
    }
    tsFiles[`error-codes/${domain}.generated.ts`] = tsDomain(group);
  }
  goFiles["error_codes.generated.go"] = header + "package common\n\n" +
    "var errorClassByCode = make(map[string]string)\n\n" +
    "type errorCodeClass struct {\n\tcode  string\n\tclass string\n}\n";
  const names = [...domains.keys()];
  const ts = header + names.map((name) =>
    `import * as domain_${name} from "./error-codes/${name}.generated";\n`).join("") + "\n" +
    "export const ERROR_CODES = [\n" + names.map((name) => `  ...domain_${name}.codes,\n`).join("") + "] as const;\n\n" +
    "export type ErrorCode = (typeof ERROR_CODES)[number];\n\n" +
    `export type ErrorClass =\n  ${ERROR_CLASSES.map((errorClass) => JSON.stringify(errorClass)).join(" | ")};\n\n` +
    "export const ERROR_CODE_CLASSES: Record<ErrorCode, ErrorClass> = {\n" +
    names.map((name) => `  ...domain_${name}.classes,\n`).join("") + "};\n\n" +
    "export const ERROR_CODE_PARAMETERS: Record<ErrorCode, readonly string[]> = {\n" +
    names.map((name) => `  ...domain_${name}.parameters,\n`).join("") + "};\n";
  return { goFiles, ts, tsFiles };
}

function generatedNames(directory, pattern) {
  try { return readdirSync(directory).filter((name) => pattern.test(name)); }
  catch (error) { if (error.code === "ENOENT") return []; throw error; }
}

// These generated namespaces are exclusive. Check mode never repairs output.
export function writeGenerated(root, { goFiles, ts, tsFiles = {} }, { check = false } = {}) {
  const directory = join(root, "backend", "api", "common");
  const frontend = join(root, "frontend", "src", "lib");
  const stale = generatedNames(directory, /^error_codes_[a-z0-9_]+\.generated\.go$/)
    .filter((name) => !(name in goFiles)).map((name) => join(directory, name));
  stale.push(...generatedNames(join(frontend, "error-codes"), /^[a-z][a-z0-9_]*\.generated\.ts$/)
    .filter((name) => !(`error-codes/${name}` in tsFiles)).map((name) => join(frontend, "error-codes", name)));
  const outputs = Object.entries(goFiles).map(([name, content]) => [join(directory, name), content]);
  outputs.push([join(frontend, "error-codes.generated.ts"), ts]);
  outputs.push(...Object.entries(tsFiles).map(([name, content]) => [join(frontend, name), content]));
  if (check) {
    const drift = [...stale];
    for (const [path, content] of outputs) {
      try { if (readFileSync(path, "utf8") !== content) drift.push(path); }
      catch (error) { if (error.code !== "ENOENT") throw error; drift.push(path); }
    }
    if (drift.length) throw new Error(`generated error codes are stale; run node scripts/generate-error-codes.mjs:\n${drift.join("\n")}`);
    return;
  }
  for (const path of stale) unlinkSync(path);
  for (const [path, content] of outputs) {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === realpathSync(process.argv[1])) {
  writeGenerated(root, generate(readRegistry(root)), { check: process.argv.includes("--check") });
}
