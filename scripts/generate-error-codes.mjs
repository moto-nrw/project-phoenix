#!/usr/bin/env node
import { readFileSync, readdirSync, realpathSync, unlinkSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const registryPath = join(root, "error-registry.json");
const codePattern = /^[a-z][a-z0-9_]*\.[a-z][a-z0-9_]*$/;
const parameterPattern = /^[a-z][a-z0-9_]*$/;
const errorClasses = ["input", "permission", "business_rejection", "unavailable", "server"];
const classes = new Set(errorClasses);

export function validateRegistry(registry) {
  if (!registry || !Array.isArray(registry.codes)) throw new Error("registry.codes must be an array");
  const codes = new Set();
  const legacy = new Set();
  const symbols = new Set();
  for (const entry of registry.codes) {
    if (!codePattern.test(entry.code)) throw new Error(`invalid error code: ${entry.code}`);
    if (codes.has(entry.code)) throw new Error(`duplicate error code: ${entry.code}`);
    codes.add(entry.code);
    if (!classes.has(entry.class)) throw new Error(`invalid class for ${entry.code}: ${entry.class}`);
    if (!Array.isArray(entry.parameters)) throw new Error(`parameters must be an array: ${entry.code}`);
    const parameters = new Set();
    for (const parameter of entry.parameters) {
      if (!parameterPattern.test(parameter) || parameters.has(parameter)) {
        throw new Error(`invalid or duplicate parameter for ${entry.code}: ${parameter}`);
      }
      parameters.add(parameter);
    }
    if (typeof entry.legacy !== "string" || !entry.legacy) throw new Error(`missing legacy code: ${entry.code}`);
    if (legacy.has(entry.legacy)) throw new Error(`duplicate legacy code: ${entry.legacy}`);
    legacy.add(entry.legacy);
    const symbol = goSymbol(entry.code);
    if (symbols.has(symbol)) throw new Error(`duplicate Go symbol: ${symbol}`);
    symbols.add(symbol);
  }
  return [...registry.codes].sort((a, b) => a.code.localeCompare(b.code, "en"));
}

function goSymbol(code) {
  return "Code" + code.split(/[._]/).map((part) => part[0].toUpperCase() + part.slice(1)).join("");
}

export function generate(registry) {
  const entries = validateRegistry(registry);
  const header = "// Code generated by scripts/generate-error-codes.mjs; DO NOT EDIT.\n";
  // Two declaration lines per code plus file framing: at most 615 lines,
  // leaving every generated file inside the unchanged 800-line source gate.
  const shards = [];
  for (let offset = 0; offset < entries.length; offset += 300) {
    shards.push(entries.slice(offset, offset + 300));
  }
  const goFiles = {};
  shards.forEach((shard, index) => {
    const symbolWidth = Math.max(...shard.map((entry) => goSymbol(entry.code).length));
    const codeKeyWidth = Math.max(...shard.map((entry) => JSON.stringify(entry.code).length + 1));
    const name = `error_codes_${String(index).padStart(3, "0")}.generated.go`;
    goFiles[name] = header + "package common\n\nconst (\n" + shard.map((entry) =>
      `\t${goSymbol(entry.code).padEnd(symbolWidth)} = ${JSON.stringify(entry.code)}\n`).join("") + ")\n\n" +
      `var errorCodeClasses${index} = map[string]string{\n` + shard.map((entry) =>
        `\t${(`${JSON.stringify(entry.code)}:`).padEnd(codeKeyWidth)} ${JSON.stringify(entry.class)},\n`).join("") + "}\n\n" +
      "func init() {\n" +
      `\tfor code, class := range errorCodeClasses${index} {\n` +
      "\t\terrorClassByCode[code] = class\n" +
      "\t}\n" +
      `\terrorCodeClasses${index} = nil\n` +
      "}\n";
  });
  goFiles["error_codes.generated.go"] = header + "package common\n\n" +
    "var errorClassByCode = make(map[string]string)\n";
  const ts = header + "export const ERROR_CODES = [\n" + entries.map((entry) =>
    `  ${JSON.stringify(entry.code)},\n`).join("") + "] as const;\n\n" +
    "export type ErrorCode = (typeof ERROR_CODES)[number];\n\n" +
    `export type ErrorClass =\n  ${errorClasses.map((errorClass) => JSON.stringify(errorClass)).join(" | ")};\n\n` +
    "export const ERROR_CODE_CLASSES: Record<ErrorCode, ErrorClass> = {\n" + entries.map((entry) =>
      `  ${JSON.stringify(entry.code)}: ${JSON.stringify(entry.class)},\n`).join("") + "};\n\n" +
    "export const ERROR_CODE_PARAMETERS: Record<ErrorCode, readonly string[]> = {\n" + entries.map((entry) => {
      const prefix = `  ${JSON.stringify(entry.code)}: `;
      const values = entry.parameters.map((parameter) => JSON.stringify(parameter));
      const inline = `[${values.join(", ")}]`;
      return prefix.length + inline.length + 1 <= 80
        ? `${prefix}${inline},\n`
        : `${prefix}[\n${values.map((value) => `    ${value},\n`).join("")}  ],\n`;
    }).join("") + "};\n";
  return { goFiles, ts };
}

// The numbered namespace belongs to this generator. Remove stale shards on
// regeneration, and reject missing, changed or extra output in read-only mode.
export function writeGenerated(root, { goFiles, ts }, { check = false } = {}) {
  const directory = join(root, "backend", "api", "common");
  const stale = readdirSync(directory).filter((name) =>
    /^error_codes_[0-9]{3,}\.generated\.go$/.test(name) && !(name in goFiles));
  const outputs = Object.entries(goFiles).map(([name, content]) => [join(directory, name), content]);
  outputs.push([join(root, "frontend", "src", "lib", "error-codes.generated.ts"), ts]);
  if (check) {
    const drift = stale.map((name) => join(directory, name));
    for (const [path, content] of outputs) {
      try {
        if (readFileSync(path, "utf8") !== content) drift.push(path);
      } catch (error) {
        if (error.code !== "ENOENT") throw error;
        drift.push(path);
      }
    }
    if (drift.length) throw new Error(`generated error codes are stale; run node scripts/generate-error-codes.mjs:\n${drift.join("\n")}`);
    return;
  }
  for (const name of stale) unlinkSync(join(directory, name));
  for (const [path, content] of outputs) writeFileSync(path, content);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === realpathSync(process.argv[1])) {
  const registry = JSON.parse(readFileSync(registryPath, "utf8"));
  writeGenerated(root, generate(registry), { check: process.argv.includes("--check") });
}
